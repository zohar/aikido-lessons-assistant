create table public.aikido_seances (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  status text not null default 'generating'
    check (status in ('generating','reviewing','ready','error')),
  step text,
  theme text,
  public text,
  author text,
  request jsonb not null default '{}'::jsonb,
  data jsonb,
  versions jsonb not null default '[]'::jsonb,
  error text
);
comment on table public.aikido_seances is 'Carnet de séances Aïkido: lessons generated by the n8n workflow. Accessed only through n8n (service role); no client access.';
create index aikido_seances_updated_at_idx on public.aikido_seances (updated_at desc);
create or replace function public.aikido_seances_touch()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
create trigger aikido_seances_touch before update on public.aikido_seances
for each row execute function public.aikido_seances_touch();
alter table public.aikido_seances enable row level security;
